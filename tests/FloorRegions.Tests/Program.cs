using RevitMCP.Core;
using NetTopologySuite.Geometries;
var f=PlanarFloorRegions.Factory;
Polygon Box(double x,double y,double w,double h)=>f.CreatePolygon(new[]{new Coordinate(x,y),new Coordinate(x+w,y),new Coordinate(x+w,y+h),new Coordinate(x,y+h),new Coordinate(x,y)});
void Check(bool ok,string name){if(!ok)throw new Exception(name);Console.WriteLine("PASS "+name);}
var frame=new List<Geometry>{Box(0,0,10000,500),Box(0,9500,10000,500),Box(0,500,500,9000),Box(9500,500,500,9000)};
var a=PlanarFloorRegions.Find(frame);Check(a.Count==1&&Math.Abs(a[0].Area-81000000)<1,"single inner clear bay");
Check(PlanarFloorRegions.Find(frame.Take(3)).Count==0,"open perimeter never closed");
var split=frame.Concat(new[]{Box(4750,500,500,9000)}).ToList();
var b=PlanarFloorRegions.Find(split);Check(b.Count==2&&Math.Abs(b.Sum(x=>x.Area)-76500000)<1,"divider creates two bays");
var c=PlanarFloorRegions.Find(frame.Concat(new[]{Box(4000,4000,1000,1000)}));
Check(c.Count==1&&c[0].NumInteriorRings==1&&Math.Abs(c[0].Area-80000000)<1,"internal column becomes hole");
var duplicate=PlanarFloorRegions.Find(frame.Concat(frame));Check(duplicate.Count==1&&duplicate[0].Area==a[0].Area,"duplicate source footprints are idempotent");
var d=PlanarFloorRegions.Find(frame.Concat(new[]{Box(0,0,2000,2000)}));Check(d.Count==1&&Math.Abs(d[0].Area-78750000)<1,"corner column clips net boundary");
var gap=new List<Geometry>{Box(0,0,4999,500),Box(5001,0,4999,500),frame[1],frame[2],frame[3]};
Check(PlanarFloorRegions.Find(gap).Count==0,"2 mm gap is not bridged");
Check(PlanarFloorRegions.Key(a[0])==PlanarFloorRegions.Key(a[0].Reverse()),"region key ignores winding");
var islands=frame.Concat(new[]{Box(3000,3000,4000,200),Box(3000,6800,4000,200),Box(3000,3200,200,3600),Box(6800,3200,200,3600)});
var nested=PlanarFloorRegions.Find(islands);Check(nested.Count==2,"nested closed framing has two nonoverlapping regions");
Check(nested[0].Intersection(nested[1]).Area==0,"nested regions never overlap");
var rotated=NetTopologySuite.Geometries.Utilities.AffineTransformation.RotationInstance(Math.PI/5);
var diagonal=PlanarFloorRegions.Find(frame.Select(g=>rotated.Transform(g)));
Check(diagonal.Count==1&&Math.Abs(diagonal[0].Area-a[0].Area)<100,"diagonal frame supported");
Check(a[0].Intersection(Box(1000,1000,2000,2000)).Area>1,"existing floor overlap detectable");
var beamsWithCornerGaps=new Geometry[]{Box(1000,0,8000,500),Box(1000,9500,8000,500),Box(0,1000,500,8000),Box(9500,1000,500,8000)};
Check(PlanarFloorRegions.Find(beamsWithCornerGaps).Count==0,"beam-only gaps remain open");
var withColumns=beamsWithCornerGaps.Concat(new[]{Box(0,0,1000,1000),Box(9000,0,1000,1000),Box(0,9000,1000,1000),Box(9000,9000,1000,1000)});
var colClosed=PlanarFloorRegions.Find(withColumns);
Check(colClosed.Count==1&&Math.Abs(colClosed[0].Area-80000000)<1,"columns can complete a beam-column enclosure");
Check(PlanarFloorRegions.IsNearExcluded(Box(0,0,1000,1000),Box(1000,200,200,200)),"touching unsupported member excludes entire bay");
Check(!PlanarFloorRegions.IsNearExcluded(Box(0,0,1000,1000),Box(2000,2000,100,100)),"remote bay remains eligible");
Check(PlanarFloorRegions.IsNearExcluded(c[0],Box(4000,4000,1000,1000)),"unsupported column island quarantines surrounding bay");
Console.WriteLine("17 geometry checks passed");
var bays=new List<Polygon>{Box(0,0,3000,700),Box(0,-1200,3000,600)};
Check(PlanarFloorRegions.LabelRegion(bays,new Coordinate(1400,-65.24),100,100)==0,"S25 65mm outside clear edge pairs uniquely");
Check(PlanarFloorRegions.LabelRegion(bays,new Coordinate(1400,-65.24),0,100)==-1,"boundary recovery opt-in");
Check(PlanarFloorRegions.LabelRegion(bays,new Coordinate(1400,-300),300,100)==-1,"equidistant neighbor not guessed");
Check(PlanarFloorRegions.LabelRegion(bays,new Coordinate(1400,-101),100,100)==-1,"outside tolerance rejected");
Check(PlanarFloorRegions.LabelRegion(bays,new Coordinate(1400,0),0,100)==0,"point exactly on boundary accepted");
Check(PlanarFloorRegions.LabelRegion(c,new Coordinate(4001,4500),100,100)==-1,"column hole not assigned to surrounding floor");
